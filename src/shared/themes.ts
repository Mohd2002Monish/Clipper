export function applyThemeToSettings(
  theme: IThemePreset,
  currentOverlay: TextOverlaySettings,
  currentSubs?: AISubtitleSettings
): { newOverlay: TextOverlaySettings; newSubs?: AISubtitleSettings } {
  const newOverlay: TextOverlaySettings = {
    ...currentOverlay,
    themePreset: theme.id,
    top: {
      ...currentOverlay.top,
      ...(theme.top || {}),
      // preserve user text content if already typed
      text: currentOverlay.top.text || 'Part {part}/{total} • {title}',
      mode: currentOverlay.top.mode,
      perPartTexts: currentOverlay.top.perPartTexts,
    },
    bottom: {
      ...currentOverlay.bottom,
      ...(theme.bottom || {}),
      // preserve user text content if already typed
      text: currentOverlay.bottom.text || 'Follow for more updates',
      mode: currentOverlay.bottom.mode,
      perPartTexts: currentOverlay.bottom.perPartTexts,
    },
  };

  let newSubs = currentSubs;
  if (currentSubs && theme.aiSubtitles) {
    newSubs = {
      ...currentSubs,
      ...theme.aiSubtitles,
      subtitles: currentSubs.subtitles,
      enabled: currentSubs.enabled,
    };
  }

  return { newOverlay, newSubs };
}
